const DICTS: Record<Lang, Dict> = {
  en,
  ua,
  de,
  es,
  fr,
  pl,
  pt,
  ro,
  hu,
  bg,
  zh,
};

const CODES = LANGUAGES.map((l) => l.code);

let current: Lang = readInitialLang();
const listeners = new Set<() => void>();

function readInitialLang(): Lang {
  const stored = localStorage.getItem("bs-lang");
  if (stored === "uk") return "ua"; // migrate the old ISO code
  if (stored && CODES.includes(stored as Lang)) return stored as Lang;
  return "en";
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  localStorage.setItem("bs-lang", lang);
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn());
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

function interpolate(message: string, values?: MessageValues): string {
  if (!values) return message;
  return message.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
  );
}

export function useI18n() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  const t: Translate = (key, values) => interpolate(DICTS[lang][key] ?? en[key], values);
  return { lang, setLang, t };
}
