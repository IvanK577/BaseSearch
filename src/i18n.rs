use crate::db_types::StartupPhase;

/// The label for what opening the database is doing right now.
pub fn startup_phase_label(phase: StartupPhase, t: &Tr) -> &'static str {
    match phase {
        StartupPhase::CheckingVersion => t.phase_checking_version,
        StartupPhase::CheckingFreeSpace => t.phase_checking_space,
        StartupPhase::CreatingBackup => t.phase_backup,
        StartupPhase::VerifyingBackup => t.phase_verify_backup,
        StartupPhase::UpgradingStructure => t.phase_upgrading,
        StartupPhase::RebuildingFingerprints { .. } => t.phase_fingerprints,
        StartupPhase::ComputingTypedColumns { .. } => t.phase_typed_columns,
        StartupPhase::VerifyingUpgrade => t.phase_verifying,
    }
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Ua => "ua",
            Lang::De => "de",
            Lang::Es => "es",
            Lang::Fr => "fr",
            Lang::Pl => "pl",
            Lang::Pt => "pt",
            Lang::Ro => "ro",
            Lang::Hu => "hu",
            Lang::Bg => "bg",
            Lang::Zh => "zh",
        }
    }

    pub fn from_code(code: &str) -> Lang {
        match code {
            "ua" => Lang::Ua,
            "de" => Lang::De,
            "es" => Lang::Es,
            "fr" => Lang::Fr,
            "pl" => Lang::Pl,
            "pt" => Lang::Pt,
            "ro" => Lang::Ro,
            "hu" => Lang::Hu,
            "bg" => Lang::Bg,
            "zh" => Lang::Zh,
            _ => Lang::En,
        }
    }

    /// Best match for an operating-system locale tag such as `uk_UA.UTF-8`,
    /// `pt-BR`, or `zh-Hans-CN`.
    ///
    /// Only the primary subtag is consulted. `uk` is Ukrainian's ISO code
    /// while this app spells the language `ua`, so both are accepted. An
    /// unknown tag returns `None` rather than quietly meaning English, because
    /// callers need to tell "no preference stated" from "chose English".
    pub fn from_locale_tag(tag: &str) -> Option<Lang> {
        let primary = tag
            .split(['.', '@', '_', '-'])
            .next()
            .unwrap_or_default()
            .to_ascii_lowercase();
        match primary.as_str() {
            "en" => Some(Lang::En),
            "ua" | "uk" => Some(Lang::Ua),
            "de" => Some(Lang::De),
            "es" => Some(Lang::Es),
            "fr" => Some(Lang::Fr),
            "pl" => Some(Lang::Pl),
            "pt" => Some(Lang::Pt),
            "ro" => Some(Lang::Ro),
            "hu" => Some(Lang::Hu),
            "bg" => Some(Lang::Bg),
            "zh" => Some(Lang::Zh),
            _ => None,
        }
    }

    /// Language for the screens that appear before a database is open, and so
    /// before the stored preference can be read: the workspace prompts. Reads
    /// the usual locale variables and gives up rather than guessing.
    pub fn from_environment() -> Option<Lang> {
        ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"]
            .into_iter()
            .filter_map(|name| std::env::var(name).ok())
            .find_map(|value| value.split(':').find_map(Lang::from_locale_tag))
    }

    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ua => "Українська",
            Lang::De => "Deutsch",
            Lang::Es => "Español",
            Lang::Fr => "Français",
            Lang::Pl => "Polski",
            Lang::Pt => "Português",
            Lang::Ro => "Română",
            Lang::Hu => "Magyar",
            Lang::Bg => "Български",
            Lang::Zh => "中文",
        }
    }

    pub const ALL: [Lang; 11] = [
        Lang::En,
        Lang::Ua,
        Lang::De,
        Lang::Es,
        Lang::Fr,
        Lang::Pl,
        Lang::Pt,
        Lang::Ro,
        Lang::Hu,
        Lang::Bg,
        Lang::Zh,
    ];
}

